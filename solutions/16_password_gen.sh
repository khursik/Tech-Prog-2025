#!/bin/bash

# Задача 16: Генератор паролей
# Скрипт генерирует случайные пароли

set -euo pipefail

# Параметры по умолчанию
DEFAULT_LENGTH=12
DEFAULT_COUNT=1

# Получаем аргументы
length=${1:-$DEFAULT_LENGTH}
count=${2:-$DEFAULT_COUNT}

# Проверка корректности аргументов
if ! [[ "${length}" =~ ^[0-9]+$ ]] || [ "${length}" -lt 4 ]; then
    echo "Ошибка: длина пароля должна быть числом >= 4" >&2
    exit 1
fi

if ! [[ "${count}" =~ ^[0-9]+$ ]] || [ "${count}" -lt 1 ]; then
    echo "Ошибка: количество паролей должно быть числом >= 1" >&2
    exit 1
fi

# Файл для сохранения
output_file="passwords.txt"

echo "=== Генератор паролей ==="
echo "Длина пароля: ${length}"
echo "Количество: ${count}"
echo ""

# Создаём или очищаем файл с паролями
> "${output_file}"

# Набор символов для пароля
# Используем буквы (верхний и нижний регистр), цифры и спецсимволы
charset="A-Za-z0-9!@#$%^&*()_+-=[]{}|;:,.<>?"

echo "Сгенерированные пароли:"
echo "─────────────────────────────────────────"

# Генерируем пароли
for ((i=1; i<=count; i++)); do
    # Используем /dev/urandom для генерации случайных данных
    # tr удаляет ненужные символы, head берёт нужное количество
    password=$(LC_ALL=C tr -dc "${charset}" < /dev/urandom | head -c "${length}")

    # Выводим пароль
    printf "%2d. %s\n" "${i}" "${password}"

    # Сохраняем в файл
    echo "${password}" >> "${output_file}"
done

echo "─────────────────────────────────────────"
echo ""
echo "Пароли сохранены в файл: ${output_file}"
echo ""
echo "⚠ ВАЖНО: Храните пароли в безопасном месте!"
echo "=== Конец генерации ==="
