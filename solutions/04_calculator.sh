#!/bin/bash

# Задача 4: Калькулятор
# Скрипт выполняет простые арифметические операции

set -euo pipefail

# Проверка количества аргументов
if [ $# -ne 3 ]; then
    echo "Использование: $0 <число1> <операция> <число2>" >&2
    echo "Операции: + - * /" >&2
    exit 1
fi

# Получаем аргументы
num1=$1
operation=$2
num2=$3

# Проверка, что первый и третий аргументы - числа
if ! [[ "${num1}" =~ ^-?[0-9]+\.?[0-9]*$ ]]; then
    echo "Ошибка: '${num1}' не является числом" >&2
    exit 1
fi

if ! [[ "${num2}" =~ ^-?[0-9]+\.?[0-9]*$ ]]; then
    echo "Ошибка: '${num2}' не является числом" >&2
    exit 1
fi

# Выполняем операцию
case "${operation}" in
    +)
        result=$(echo "${num1} + ${num2}" | bc)
        ;;
    -)
        result=$(echo "${num1} - ${num2}" | bc)
        ;;
    \*)
        result=$(echo "${num1} * ${num2}" | bc)
        ;;
    /)
        if [ "${num2}" = "0" ] || [ "${num2}" = "0.0" ]; then
            echo "Ошибка: деление на ноль" >&2
            exit 1
        fi
        result=$(echo "scale=2; ${num1} / ${num2}" | bc)
        ;;
    *)
        echo "Ошибка: неизвестная операция '${operation}'" >&2
        echo "Доступные операции: + - * /" >&2
        exit 1
        ;;
esac

# Выводим результат
echo "${result}"
