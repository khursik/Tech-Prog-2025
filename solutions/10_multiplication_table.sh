#!/bin/bash

# Задача 10: Таблица умножения
# Скрипт выводит таблицу умножения для заданного числа

set -euo pipefail

# Проверка наличия аргумента
if [ $# -eq 0 ]; then
    echo "Использование: $0 <число>" >&2
    exit 1
fi

number=$1

# Проверка, что это число
if ! [[ "${number}" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: '${number}' не является числом" >&2
    exit 1
fi

echo "=== Таблица умножения для ${number} ==="
echo ""

# Выводим таблицу умножения от 1 до 10
for i in {1..10}; do
    result=$((number * i))
    printf "%2d x %2d = %4d\n" "${number}" "${i}" "${result}"
done

echo ""
echo "=== Конец таблицы ==="
