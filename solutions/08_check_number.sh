#!/bin/bash

# Задача 8: Проверка числа
# Скрипт анализирует свойства числа

set -euo pipefail

# Проверка наличия аргумента
if [ $# -eq 0 ]; then
    echo "Использование: $0 <число>" >&2
    exit 1
fi

number=$1

# Проверка, что это целое число
if ! [[ "${number}" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: '${number}' не является целым числом" >&2
    exit 1
fi

echo "=== Анализ числа: ${number} ==="
echo ""

# Проверка знака
if [ "${number}" -gt 0 ]; then
    echo "Знак: положительное"
elif [ "${number}" -lt 0 ]; then
    echo "Знак: отрицательное"
else
    echo "Знак: ноль"
fi

# Проверка чётности (только для ненулевых чисел)
if [ "${number}" -ne 0 ]; then
    if [ $((number % 2)) -eq 0 ]; then
        echo "Чётность: чётное"
    else
        echo "Чётность: нечётное"
    fi
fi

# Проверка делимости на 5
if [ $((number % 5)) -eq 0 ]; then
    echo "Делимость на 5: да"
else
    echo "Делимость на 5: нет"
fi

echo ""
echo "=== Конец анализа ==="
